# -*- coding: utf-8 -*-
"""装牙：把能查的规则写进 `.rule-teeth/rules.json`，把 engine.py 复制过去，按需挂上 Claude Code hook。

hook 写法照 Claude Code 官方文档（code.claude.com/docs/en/hooks，2026-11-21 核对）：
- PreToolUse（matcher `Write|Edit|Bash`）：exit 2 = 拦下这次工具调用，stderr 交给 Claude；
- Stop：exit 2 = 不许结束，stderr 告诉 Claude 还差什么；输入里有 stop_hook_active，官方另有连续 8 次的上限。
"""
from __future__ import annotations

import datetime as _dt
import json
import shutil
from pathlib import Path

from . import checkup, engine

HOOK_COMMAND = 'python3 "${CLAUDE_PROJECT_DIR}/.rule-teeth/engine.py" hook'
HOOK_MARK = ".rule-teeth/engine.py"
README = {
    "zh": "# .rule-teeth\n\n由 rule-teeth 从项目的 CLAUDE.md / AGENTS.md 生成。\n\n"
          "- `rules.json`：能自动查的规则（检查清单）+ 暂缓清单（欠条，带到期日）。可以手改：关掉一条就把 `enabled` 改成 false。\n"
          "- `engine.py`：检查程序，只用 Python 标准库。`python3 .rule-teeth/engine.py check` 扫全项目。\n"
          "- Claude Code 的 hook 会调用它：改文件 / 跑命令之前、结束之前，违反规则就当场拦下。\n"
          "- AI 不能自己改这个目录（hook 会拦）—— 规则松不松，由人决定。\n",
    "en": "# .rule-teeth\n\nGenerated by rule-teeth from this project's CLAUDE.md / AGENTS.md.\n\n"
          "- `rules.json`: the rules that can be checked automatically, plus the deferral list (IOUs with due dates). "
          "Edit by hand: set `enabled` to false to switch one off.\n"
          "- `engine.py`: the checker, Python standard library only. `python3 .rule-teeth/engine.py check` scans the project.\n"
          "- Claude Code hooks call it before edits / commands and before stopping; a broken rule is blocked on the spot.\n"
          "- The AI may not edit this folder (the hook blocks it) — loosening a rule is a human decision.\n",
}


def make_doc(cu: checkup.Checkup, baseline_days: int = 30) -> dict:
    doc = {"version": 1, "generated_by": f"rule-teeth {engine.VERSION}",
           "generated_at": _dt.date.today().isoformat(), "lang": cu.lang,
           "checks": checkup.build_checks(cu.rules, cu.lang), "baseline": []}
    every = {**doc, "checks": [{**c, "enabled": True} for c in doc["checks"]]}
    current = engine.check_project(cu.root, every)      # 关着的也登记，免得以后一打开就把老问题全算成新违规
    doc["baseline"] = engine.make_baseline(current, baseline_days)
    return doc


def settings_path(root: Path, local: bool) -> Path:
    return Path(root) / ".claude" / ("settings.local.json" if local else "settings.json")


def _load_settings(p: Path) -> dict:
    if not p.exists():
        return {}
    data = json.loads(p.read_text(encoding="utf-8"))      # 坏 JSON 直接报错停住，不覆盖用户的文件
    if not isinstance(data, dict):
        raise ValueError(f"{p} 不是 JSON 对象 / is not a JSON object")
    return data


def _ours(group: dict) -> bool:
    return any(HOOK_MARK in (h.get("command") or "") + " ".join(h.get("args") or []) for h in group.get("hooks", []))


def add_hooks(settings: dict) -> dict:
    hooks = settings.setdefault("hooks", {})
    wanted = {
        "PreToolUse": {"matcher": "Write|Edit|Bash",
                       "hooks": [{"type": "command", "command": HOOK_COMMAND, "statusMessage": "rule-teeth"}]},
        "Stop": {"hooks": [{"type": "command", "command": HOOK_COMMAND, "statusMessage": "rule-teeth"}]},
    }
    for event, group in wanted.items():
        groups = hooks.setdefault(event, [])
        if not any(_ours(g) for g in groups):
            groups.append(group)
    return settings


def remove_hooks(settings: dict) -> dict:
    hooks = settings.get("hooks") or {}
    for event in list(hooks):
        hooks[event] = [g for g in hooks[event] if not _ours(g)]
        if not hooks[event]:
            del hooks[event]
    if "hooks" in settings and not settings["hooks"]:
        del settings["hooks"]
    return settings


def write_settings(root: Path, local: bool, change) -> Path:
    p = settings_path(root, local)
    data = _load_settings(p)
    if p.exists():
        shutil.copy2(p, p.with_name(p.name + ".bak-rule-teeth"))
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(change(data), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return p


def init(root, hook: bool = False, local: bool = False, dry_run: bool = False, include=(),
         baseline_days: int = 30) -> dict:
    root = Path(root).resolve()
    cu = checkup.run(root, include)
    doc = make_doc(cu, baseline_days)
    summary = {"root": str(root), "lang": cu.lang, "checks": doc["checks"], "baseline": doc["baseline"],
               "written": [], "dry_run": dry_run}
    if dry_run:
        return summary
    d = root / engine.RULES_DIR
    d.mkdir(exist_ok=True)
    (d / engine.RULES_FILE).write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    shutil.copy2(Path(engine.__file__), d / "engine.py")
    (d / ".gitignore").write_text(engine.STATE_FILE + "\n", encoding="utf-8")
    (d / "README.md").write_text(README[cu.lang], encoding="utf-8")
    summary["written"] += [str(d / engine.RULES_FILE), str(d / "engine.py")]
    if hook:
        summary["written"].append(str(write_settings(root, local, add_hooks)))
    return summary


def unhook(root, local: bool = False) -> Path | None:
    root = Path(root).resolve()
    if not settings_path(root, local).exists():
        return None
    return write_settings(root, local, remove_hooks)
